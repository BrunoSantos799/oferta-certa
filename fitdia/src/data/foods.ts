export const FOODS: Food[] = ROWS.map(([id, name, kcal, protein, carbs, fat, category, portions]) => ({
  id,
  name,
  kcal,
  protein,
  carbs,
  fat,
  category,
  // Toda comida também aceita gramas; "100 g" é sempre a primeira referência
  portions,
}));

export function findFood(id: string, custom: Food[] = []): Food | undefined {
  return custom.find((f) => f.id === id) ?? FOODS.find((f) => f.id === id);
}

/** Calcula calorias e macros para uma quantidade em gramas */
export function nutrientsFor(food: Pick<Food, 'kcal' | 'protein' | 'carbs' | 'fat'>, grams: number) {
  const f = grams / 100;
  return { kcal: food.kcal * f, protein: food.protein * f, carbs: food.carbs * f, fat: food.fat * f };
}
